"""Generate the Episode 1 voice track with Kokoro-82M (Apache-2.0).

usage: python3 make_voices.py MODEL.onnx VOICES_DIR LINES.json OUT_DIR JS_OUT [MP3_NAME]

MODEL.onnx  - Kokoro-82M v1.0 ONNX export (input_ids/style/speed)
VOICES_DIR  - folder of <voice>.bin style files (510x256 float32), e.g. from the kokoro-js npm package
Writes OUT_DIR/voices.mp3 (one sprite of every line) and JS_OUT (timings + lip-sync envelopes).
"""
import json, os, subprocess, sys, tempfile
import numpy as np
import soundfile as sf
import librosa
from kokoro_onnx import Kokoro

SR = 24000
model, vdir, lines_path, out_dir, js_out = sys.argv[1:6]
mp3_name = sys.argv[6] if len(sys.argv) > 6 else 'voices.mp3'  # e.g. ep02.mp3 for later episodes
spec = json.load(open(lines_path))

# kokoro-onnx wants an .npz of named voices shaped (510, 1, 256)
names = sorted({v for c in spec['cast'].values() for v, _ in c['voice']})
tmp = tempfile.mkdtemp()
npz = os.path.join(tmp, 'voices.npz')
np.savez(npz, **{n: np.fromfile(os.path.join(vdir, n + '.bin'), dtype=np.float32).reshape(510, 1, 256) for n in names})
os.rename(npz, npz.replace('.npz', '.bin'))
tts = Kokoro(model, npz.replace('.npz', '.bin'))

def style(cast):
    return sum(tts.get_voice_style(v) * w for v, w in cast['voice']).astype(np.float32)

def demon(y):
    a = librosa.effects.pitch_shift(y, sr=SR, n_steps=-4)
    b = librosa.effects.pitch_shift(y, sr=SR, n_steps=-12) * 0.5
    z = a + b
    return np.tanh(z * 2.2) / np.tanh(2.2)

def static(y):
    z = librosa.effects.pitch_shift(y, sr=SR, n_steps=-2)
    t = np.arange(len(z)) / SR
    z = z * (0.86 + 0.14 * np.sin(2 * np.pi * 47 * t))
    rng = np.random.default_rng(7)
    crackle = np.zeros_like(z)
    for i in rng.integers(0, len(z), size=max(1, len(z) // 2400)):
        n = int(rng.integers(20, 90)); crackle[i:i + n] += rng.normal(0, 0.06, size=len(crackle[i:i + n]))
    return z + crackle * (np.abs(z).mean() * 6)

def level(y, target_db=-19.0):
    rms = np.sqrt(np.mean(y ** 2) + 1e-12)
    y = y * (10 ** (target_db / 20) / rms)
    pk = np.abs(y).max()
    return y * (0.89 / pk) if pk > 0.89 else y

pad0, gap = int(0.25 * SR), int(0.4 * SR)
track = [np.zeros(pad0, np.float32)]
pos = pad0
meta = {}
for ln in spec['lines']:
    cast = spec['cast'][ln['who']]
    text = ln.get('tts', ln['text'])
    y, _ = tts.create(text, voice=style(cast), speed=ln.get('speed', cast['speed']), lang='en-us')
    y = y.astype(np.float32)
    if cast.get('fx') == 'demon': y = demon(y)
    if cast.get('fx') == 'static': y = static(y)
    y = level(y).astype(np.float32)
    hop = SR // 30  # lip-sync envelope at 30 fps
    env = [float(np.sqrt(np.mean(y[i:i + hop] ** 2))) for i in range(0, len(y), hop)]
    mx = max(env) or 1
    meta[ln['id']] = {'who': ln['who'], 'text': ln['text'], 'mono': bool(ln.get('mono')),
                      'off': round(pos / SR, 4), 'dur': round(len(y) / SR, 3),
                      'env': ''.join(str(min(9, int(9.99 * (e / mx) ** 0.8))) for e in env)}
    track += [y, np.zeros(gap, np.float32)]
    pos += len(y) + gap
    print(f"{ln['id']:>4} {ln['who']:<7} {len(y) / SR:5.2f}s  {ln['text']}", flush=True)

os.makedirs(out_dir, exist_ok=True)
wav = os.path.join(tmp, 'voices.wav')
sf.write(wav, np.concatenate(track), SR)
subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-ar', str(SR), '-c:a', 'libmp3lame', '-b:a', '64k', os.path.join(out_dir, mp3_name)], check=True)
with open(js_out, 'w') as f:
    f.write('/* generated by tools/make_voices.py: voice sprite timings and lip-sync envelopes (30 fps) */\n')
    f.write("const VOICE_DATA = " + json.dumps({'file': 'voice/' + mp3_name, 'lines': meta}, separators=(',', ':')) + ';\n')
print('total', round(pos / SR, 1), 's')
